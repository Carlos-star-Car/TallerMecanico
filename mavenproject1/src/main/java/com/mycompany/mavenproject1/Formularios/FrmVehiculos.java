    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed

        String placa = txtPlaca.getText().trim();
        String marca = txtMarca.getText().trim();
        String modelo = txtModelo.getText().trim();
        String color = txtColor.getText().trim();
        String tipo = txtTipo.getText().trim();
        Object seleccion = jCBCodigoCliente.getSelectedItem();

        if (placa.isEmpty() || marca.isEmpty() || modelo.isEmpty()
                || color.isEmpty() || tipo.isEmpty() || seleccion == null) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Debe completar todos los campos y existir al menos un cliente.");
            return;
        }

        Vehiculo vehiculo = new Vehiculo(placa, marca, modelo, color, tipo, seleccion.toString());

        if (modoModificar) {
            servicio.modificar(vehiculo);
            javax.swing.JOptionPane.showMessageDialog(this, "Vehículo modificado.");
            modoModificar = false;
            txtPlaca.setEnabled(true);
        } else {
            if (!servicio.guardar(vehiculo)) {
                javax.swing.JOptionPane.showMessageDialog(this, "Ya existe un vehículo con esa placa.");
                return;
            }
            javax.swing.JOptionPane.showMessageDialog(this, "Vehículo guardado.");
        }

        actualizarTabla();
        limpiarCampos();

        // TODO add your handling code here:
    }//GEN-LAST:event_btnGuardarActionPerformed


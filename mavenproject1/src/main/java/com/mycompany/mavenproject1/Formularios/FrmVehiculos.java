private void mostrarNombreCliente() {
    Object seleccion = jCBCodigoCliente.getSelectedItem();
    if (seleccion == null) {
        lblNombreCliente.setText("");
        return;
    }
    Cliente c = clienteServicio.buscarPorCodigo(seleccion.toString());
    lblNombreCliente.setText(c == null ? "" : " " + c.getNombreCompleto());
}
    private void cargarClientes() {
        jCBCodigoCliente.removeAllItems();
        for (Cliente c : clienteServicio.listar()) {
            jCBCodigoCliente.addItem(c.getCodigo());
        }
    }

    private void actualizarTabla() {
        mostrarEnTabla(servicio.listar());
    }

    private void mostrarEnTabla(java.util.List<Vehiculo> lista) {
        javax.swing.table.DefaultTableModel modelo = new javax.swing.table.DefaultTableModel(
                new Object[]{"Placa", "Marca", "Modelo", "Color", "Tipo", "Cód. cliente"}, 0
        ) {
            @Override
            public boolean isCellEditable(int fila, int columna) {
                return false;
            }
        };
        for (Vehiculo v : lista) {
            modelo.addRow(new Object[]{
                v.getPlaca(), v.getMarca(), v.getModelo(),
                v.getColor(), v.getTipo(), v.getCodigoCliente()
            });
        }
        tblVehiculos.setModel(modelo);
    }


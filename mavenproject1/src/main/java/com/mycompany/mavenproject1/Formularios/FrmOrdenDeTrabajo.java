    private void configurarFormulario() {
        txtCodigoOrden.setEditable(false);
        txtFechaDeIngreso.setEditable(false);
        txtEstado.setEditable(false);

        btnGuardar.addActionListener(e -> guardarOrden());
        btnModificar.addActionListener(e -> cargarOrdenSeleccionada());
        btnEliminar.addActionListener(e -> eliminarOrden());
        btnLimpiar.addActionListener(e -> limpiarFormulario());

        cargarCombos();
        actualizarTabla();
        limpiarFormulario();
    }

    private void cargarCombos() {
        vehiculosEnCombo = vehiculoServicio.listar();
        javax.swing.DefaultComboBoxModel<String> placas = new javax.swing.DefaultComboBoxModel<>();
        placas.addElement("-- Seleccione --");
        for (Vehiculo v : vehiculosEnCombo) {
            placas.addElement(v.getPlaca() + " - " + v.getMarca() + " " + v.getModelo());
        }
        jCBPlaca.setModel(placas);

        mecanicosEnCombo = mecanicosServicio.listar();
        javax.swing.DefaultComboBoxModel<String> mecanicos = new javax.swing.DefaultComboBoxModel<>();
        mecanicos.addElement("-- Seleccione --");
        for (Mecanicos m : mecanicosEnCombo) {
            mecanicos.addElement(m.getCodigo() + " - " + m.getNombre() + " " + m.getApellido());
        }
        jCBMecanicos.setModel(mecanicos);
    }

    private Vehiculo vehiculoSeleccionado() {
        int i = jCBPlaca.getSelectedIndex();
        return (i <= 0 || i > vehiculosEnCombo.size()) ? null : vehiculosEnCombo.get(i - 1);
    }

    private Mecanicos mecanicoSeleccionado() {
        int i = jCBMecanicos.getSelectedIndex();
        return (i <= 0 || i > mecanicosEnCombo.size()) ? null : mecanicosEnCombo.get(i - 1);
    }

    // ---------- Tabla ----------

    private void actualizarTabla() {
        javax.swing.table.DefaultTableModel modelo = new javax.swing.table.DefaultTableModel(
                new Object[]{"Código", "Fecha", "Estado", "Diagnóstico", "Placa", "Cliente", "Mecánico"}, 0) {
            @Override
            public boolean isCellEditable(int fila, int columna) {
                return false;
            }
        };
        for (OrdenDeTrabajo o : servicio.listar()) {
            modelo.addRow(new Object[]{
                o.getCodigo(),
                o.getFecha().format(FORMATO_FECHA),
                o.getEstado(),
                o.getDescripcion(),
                o.getVehiculo() == null ? "" : o.getVehiculo().getPlaca(),
                o.getCliente() == null ? "" : o.getCliente().getNombreCompleto(),
                o.getMecanico() == null ? "" : o.getMecanico().getNombre() + " " + o.getMecanico().getApellido()
            });
        }
        jtblOrdenDeServicio.setModel(modelo);
    }

    // ---------- Guardar, Modificar, Eliminar, Limpiar ----------

    private void guardarOrden() {
        String diagnostico = txtDiagnostico.getText().trim();
        if (diagnostico.isEmpty()) {
            aviso("Ingrese el diagnóstico.");
            return;
        }
        Vehiculo v = vehiculoSeleccionado();
        if (v == null) {
            aviso("Seleccione la placa del vehículo.");
            return;
        }
        Mecanicos m = mecanicoSeleccionado();
        if (m == null) {
            aviso("Seleccione el mecánico.");
            return;
        }
        // El cliente sale del vehículo, así siempre coinciden.
        Cliente c = ClienteServicio.getInstancia().buscarPorCodigo(v.getCodigoCliente());
        if (c == null) {
            aviso("El cliente del vehículo (código " + v.getCodigoCliente() + ") no existe.");
            return;
        }

        if (modoModificar) {
            OrdenDeTrabajo existente = servicio.buscarPorCodigo(txtCodigoOrden.getText());
            if (existente == null) {
                aviso("La orden ya no existe.");
                limpiarFormulario();
                return;
            }
            if (!existente.estaPendiente()) {
                aviso("No se puede modificar una orden ya facturada.");
                return;
            }
            OrdenDeTrabajo nueva = new OrdenDeTrabajo(existente.getCodigo(), c, existente.getFecha(), diagnostico);
            nueva.setVehiculo(v);
            nueva.setMecanico(m);
            nueva.setEstado(existente.getEstado());
            servicio.modificar(nueva);
            aviso("Orden modificada.");
        } else {
            String codigo = servicio.nuevoCodigo();
            OrdenDeTrabajo o = new OrdenDeTrabajo(codigo, c, LocalDate.now(), diagnostico);
            o.setVehiculo(v);
            o.setMecanico(m);
            servicio.guardar(o);
            aviso("Orden " + codigo + " guardada.");
        }
        actualizarTabla();
        limpiarFormulario();
    }

    // "Modificar": pasa la orden seleccionada en la tabla a los campos para editarla.
    private void cargarOrdenSeleccionada() {
        int fila = jtblOrdenDeServicio.getSelectedRow();
        if (fila < 0) {
            aviso("Seleccione una orden de la tabla.");
            return;
        }
        OrdenDeTrabajo o = servicio.buscarPorCodigo(jtblOrdenDeServicio.getValueAt(fila, 0).toString());
        if (o == null) {
            return;
        }
        if (!o.estaPendiente()) {
            aviso("La orden ya fue facturada y no se puede modificar.");
            return;
        }
        txtCodigoOrden.setText(o.getCodigo());
        txtFechaDeIngreso.setText(o.getFecha().format(FORMATO_FECHA));
        txtEstado.setText(o.getEstado());
        txtDiagnostico.setText(o.getDescripcion());

        jCBPlaca.setSelectedIndex(0);
        for (int i = 0; i < vehiculosEnCombo.size(); i++) {
            if (o.getVehiculo() != null
                    && vehiculosEnCombo.get(i).getPlaca().equalsIgnoreCase(o.getVehiculo().getPlaca())) {
                jCBPlaca.setSelectedIndex(i + 1);
                break;
            }
        }
        jCBMecanicos.setSelectedIndex(0);
        for (int i = 0; i < mecanicosEnCombo.size(); i++) {
            if (o.getMecanico() != null
                    && mecanicosEnCombo.get(i).getCodigo() == o.getMecanico().getCodigo()) {
                jCBMecanicos.setSelectedIndex(i + 1);
                break;
            }
        }
        modoModificar = true;
    }

    private void eliminarOrden() {
        int fila = jtblOrdenDeServicio.getSelectedRow();
        if (fila < 0) {
            aviso("Seleccione una orden de la tabla.");
            return;
        }
        String codigo = jtblOrdenDeServicio.getValueAt(fila, 0).toString();
        OrdenDeTrabajo o = servicio.buscarPorCodigo(codigo);
        if (o == null) {
            return;
        }
        if (!o.estaPendiente()) {
            aviso("No se puede eliminar una orden ya facturada.");
            return;
        }
        int respuesta = javax.swing.JOptionPane.showConfirmDialog(this,
                "¿Desea eliminar la orden " + codigo + "?",
                "Confirmar eliminación", javax.swing.JOptionPane.YES_NO_OPTION);
        if (respuesta == javax.swing.JOptionPane.YES_OPTION) {
            servicio.eliminar(codigo);
            actualizarTabla();
            limpiarFormulario();
            aviso("Orden eliminada.");
        }
    }

    private void limpiarFormulario() {
        modoModificar = false;
        txtCodigoOrden.setText(servicio.siguienteCodigo());
        txtFechaDeIngreso.setText(LocalDate.now().format(FORMATO_FECHA));
        txtEstado.setText(OrdenDeTrabajo.ESTADO_PENDIENTE);
        txtDiagnostico.setText("");
        jCBPlaca.setSelectedIndex(0);
        jCBMecanicos.setSelectedIndex(0);
        jtblOrdenDeServicio.clearSelection();
    }


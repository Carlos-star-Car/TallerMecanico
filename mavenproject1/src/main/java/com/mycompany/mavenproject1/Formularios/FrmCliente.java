    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
   String codigo = txtCodigoCliente.getText().trim();
        String nombre = txtNombreCliente.getText().trim();
        String apellido = txtApellidoCliente.getText().trim();
        String nit = txtNitCliente.getText().trim();
        String telefono = txtTelCliente.getText().trim();
        String direccion = txtDireccionCliente.getText().trim();
        String correo = txtCorreoCliente.getText().trim();

     if (codigo.isEmpty() || nombre.isEmpty() || apellido.isEmpty() || nit.isEmpty()
                || telefono.isEmpty() || direccion.isEmpty() || correo.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Debe completar todos los campos (si no tiene NIT, escriba C/F).");
            return;
    }

    Cliente cliente = new Cliente(codigo, nombre, apellido, nit, telefono, direccion, correo);

   if (modoModificar) {
            servicio.modificar(cliente);
            javax.swing.JOptionPane.showMessageDialog(this, "Cliente modificado.");
            modoModificar = false;
            txtCodigoCliente.setEnabled(true);
        } else {
            if (!servicio.guardar(cliente)) {
                javax.swing.JOptionPane.showMessageDialog(this,
                        "Ya existe un cliente con ese código.");
                return;
            }
            javax.swing.JOptionPane.showMessageDialog(this, "Cliente guardado.");
        }

    actualizarTabla();
    limpiarCampos();
        // TODO add your handling code here:
    }//GEN-LAST:event_btnGuardarActionPerformed
 

    private void mostrarEnTabla(java.util.List<Cliente> lista) {
        javax.swing.table.DefaultTableModel modelo = new javax.swing.table.DefaultTableModel(
                new Object[]{"Código", "Nombre", "Apellido", "NIT", "Teléfono", "Dirección", "Correo"}, 0
        ) {
            @Override
            public boolean isCellEditable(int fila, int columna) {
                return false;
            }
        };
        for (Cliente c : lista) {
            modelo.addRow(new Object[]{
                c.getCodigo(), c.getNombre(), c.getApellido(), c.getNit(),
                c.getTelefono(), c.getDireccion(), c.getCorreo()
            });
        }
        jtblClientes.setModel(modelo);
    }

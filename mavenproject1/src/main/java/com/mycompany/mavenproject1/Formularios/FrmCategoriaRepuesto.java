private void mostrarEnTabla(java.util.List<CategoriaRepuesto> lista) {
    javax.swing.table.DefaultTableModel modelo = new javax.swing.table.DefaultTableModel(
            new Object[]{"Código", "Nombre", "Descripción"}, 0
    ) {
        @Override
        public boolean isCellEditable(int fila, int columna) {
            return false;
        }
    };
    for (CategoriaRepuesto c : lista) {
        modelo.addRow(new Object[]{c.getCodigo(), c.getNombre(), c.getDescripcion()});
    }
    tblCategorias.setModel(modelo);
}
    private void configurarTabla() {
    modelo = new DefaultTableModel(new Object[]{"Código", "Nombre", "Descripción"}, 0) {
        @Override
        public boolean isCellEditable(int row, int col) {
            return false;
        }
    };
    tblCategorias.setModel(modelo);
    tblCategorias.setSelectionMode(javax.swing.ListSelectionModel.SINGLE_SELECTION);
}
  private void cargarImagenlogo() {
    java.net.URL url = getClass().getResource("/logotaller.png");
    if (url == null) {
        System.out.println("No se encontró la imagen");
        return;
    }
    javax.swing.ImageIcon icono = new javax.swing.ImageIcon(url);
    java.awt.Image escalada = icono.getImage().getScaledInstance(
            260, 100, java.awt.Image.SCALE_SMOOTH);
    lbllogo.setIcon(new javax.swing.ImageIcon(escalada));
    lbllogo.setText("");
}
private void llenarTabla(List<CategoriaRepuesto> lista) {
    modelo.setRowCount(0);
    for (CategoriaRepuesto c : lista) {
        modelo.addRow(new Object[]{c.getCodigo(), c.getNombre(), c.getDescripcion()});
    }
}


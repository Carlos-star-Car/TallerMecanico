    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed

    String codigoTxt = txtCodigoCategoria.getText().trim();
    String nombre = txtNombreCategoria.getText().trim();
    String descripcion = txtDescripcionCategoria.getText().trim();

    if (codigoTxt.isEmpty() || nombre.isEmpty() || descripcion.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "Debe completar todos los campos.");
        return;
    }

    int codigo;
    try {
        codigo = Integer.parseInt(codigoTxt);
    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(this, "El código debe ser un número.");
        return;
    }

    CategoriaRepuesto categoria = new CategoriaRepuesto(codigo, nombre, descripcion);

    if (modoModificar) {
        servicio.modificar(categoria);
        javax.swing.JOptionPane.showMessageDialog(this, "Categoría modificada.");
        modoModificar = false;
        txtCodigoCategoria.setEnabled(true);
    } else {
        if (!servicio.guardar(categoria)) {
            javax.swing.JOptionPane.showMessageDialog(this, "Ya existe una categoría con ese código.");
            return;
        }
        javax.swing.JOptionPane.showMessageDialog(this, "Categoría guardada.");
    }
    actualizarTabla();
    limpiarCampos();

    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnModificarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnModificarActionPerformed

    int fila = tblCategorias.getSelectedRow();
    if (fila == -1) {
        javax.swing.JOptionPane.showMessageDialog(this, "Seleccione una categoría de la tabla.");
        return;
    }
    txtCodigoCategoria.setText(tblCategorias.getValueAt(fila, 0).toString());
    txtNombreCategoria.setText(tblCategorias.getValueAt(fila, 1).toString());
    txtDescripcionCategoria.setText(tblCategorias.getValueAt(fila, 2).toString());
    txtCodigoCategoria.setEnabled(false);
    modoModificar = true;

    }//GEN-LAST:event_btnModificarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed

    int fila = tblCategorias.getSelectedRow();
    if (fila == -1) {
        javax.swing.JOptionPane.showMessageDialog(this, "Seleccione una categoría de la tabla.");
        return;
    }
    int codigo = Integer.parseInt(tblCategorias.getValueAt(fila, 0).toString());
    String nombre = tblCategorias.getValueAt(fila, 1).toString();

    int respuesta = javax.swing.JOptionPane.showConfirmDialog(this,
            "¿Desea eliminar la categoría " + nombre + " (código " + codigo + ")?",
            "Confirmar eliminación", javax.swing.JOptionPane.YES_NO_OPTION);

    if (respuesta == javax.swing.JOptionPane.YES_OPTION) {
        if (servicio.eliminar(codigo)) {
            actualizarTabla();
            limpiarCampos();
            javax.swing.JOptionPane.showMessageDialog(this, "Categoría eliminada.");
        } else {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "No se pudo eliminar la categoría. Verifique que ningún repuesto la esté usando.");
        }
    }
       // TODO add your handling code here:
    }//GEN-LAST:event_btnEliminarActionPerformed

    private void btbBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btbBuscarActionPerformed

    String codigoTxt = txtCodigoCategoria.getText().trim();
    String nombre = txtNombreCategoria.getText().trim();

    if (codigoTxt.isEmpty() && nombre.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this,
                "Ingrese un código o parte del nombre para buscar.");
        return;
    }

    int codigo = -1;
    if (!codigoTxt.isEmpty()) {
        try {
            codigo = Integer.parseInt(codigoTxt);
        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "El código debe ser un número.");
            return;
        }
    }

    java.util.List<CategoriaRepuesto> resultado = servicio.buscar(codigo, nombre);
    if (resultado.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "La categoría no existe.");
        limpiarCampos();
        actualizarTabla();
    } else {
        mostrarEnTabla(resultado);
    }
      // TODO add your handling code here:
    }//GEN-LAST:event_btbBuscarActionPerformed


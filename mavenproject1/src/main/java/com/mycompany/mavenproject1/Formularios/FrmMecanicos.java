    private void tblMecanicosMouseClicked(java.awt.event.MouseEvent evt) {
    int fila = tblMecanicos.getSelectedRow();
    if (fila < 0) {
        return;
    }
    try {
        int codigo = Integer.parseInt(tblMecanicos.getValueAt(fila, 0).toString());
        Mecanicos m = servicio.buscar(codigo);
        if (m != null) {
            cargarCampos(m);
        }
    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(this,
                "No se pudo leer el código de la fila seleccionada.");
    }
    
}
private void mostrarEnTabla(java.util.List<Mecanicos> lista) {
    javax.swing.table.DefaultTableModel modelo = new javax.swing.table.DefaultTableModel(
            new Object[]{"Código", "Nombre", "Apellido", "Telefono", "Especialidad", "Tarifa"}, 0
    ) {
        @Override
        public boolean isCellEditable(int fila, int columna) {
            return false;
        }
    };
    for (Mecanicos m : lista) {
       modelo.addRow(new Object[]{m.getCodigo(), m.getNombre(), m.getApellido(),
        m.getTelefono(), m.getEspecialidad(), m.getTarifa()});
    }
    tblMecanicos.setModel(modelo);
}


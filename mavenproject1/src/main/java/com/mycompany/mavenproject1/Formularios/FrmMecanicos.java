    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
   String codigoTxt = txtCodigoMecanico.getText().trim();
    if (codigoTxt.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "Ingrese el código a buscar.");
        return;
    }
    int codigo;
    try {
        codigo = Integer.parseInt(codigoTxt);
    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(this, "El código debe ser un número.");
        return;
    }

    Mecanicos m = servicio.buscar(codigo);
    if (m == null) {
        javax.swing.JOptionPane.showMessageDialog(this, "No se encontró el mecánico.");
        return;
    }
    cargarCampos(m);
        // TODO add your handling code here:
    }//GEN-LAST:event_btnBuscarActionPerformed

    private void btnModificarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnModificarActionPerformed
   int fila = tblMecanicos.getSelectedRow();
    Mecanicos m = null;

    if (fila >= 0) {
        int codigo = Integer.parseInt(tblMecanicos.getValueAt(fila, 0).toString());
        m = servicio.buscar(codigo);
    } else if (!txtCodigoMecanico.getText().trim().isEmpty()) {
        try {
            m = servicio.buscar(Integer.parseInt(txtCodigoMecanico.getText().trim()));
        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "El código debe ser un número.");
            return;
        }
    }

    if (m == null) {
        javax.swing.JOptionPane.showMessageDialog(this,
                "Seleccione un mecánico de la tabla o busque uno por código.");
        return;
    }

    cargarCampos(m);
    modoModificar = true;
    txtCodigoMecanico.setEnabled(false); // el código no se puede cambiar
    javax.swing.JOptionPane.showMessageDialog(this,
            "Edite los datos y presione Guardar.");

        // TODO add your handling code here:
    }//GEN-LAST:event_btnModificarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
 int fila = tblMecanicos.getSelectedRow();
    int codigo;

    try {
        if (fila >= 0) {
            codigo = Integer.parseInt(tblMecanicos.getValueAt(fila, 0).toString());
        } else {
            codigo = Integer.parseInt(txtCodigoMecanico.getText().trim());
        }
    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(this,
                "Seleccione un mecánico de la tabla o ingrese su código.");
        return;
    }

    int op = javax.swing.JOptionPane.showConfirmDialog(this,
            "¿Eliminar al mecánico con código " + codigo + "?",
            "Confirmar", javax.swing.JOptionPane.YES_NO_OPTION);
    if (op != javax.swing.JOptionPane.YES_OPTION) {
        return;
    }

    if (servicio.eliminar(codigo)) {
        javax.swing.JOptionPane.showMessageDialog(this, "Mecánico eliminado.");
        actualizarTabla();
        limpiarCampos();
    } else {
        javax.swing.JOptionPane.showMessageDialog(this, "No existe un mecánico con ese código.");
    }
        // TODO add your handling code here:
    }//GEN-LAST:event_btnEliminarActionPerformed


    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
 String codigoTxt = txtCodigoMecanico.getText().trim();
String nombre = txtNombreMecanico.getText().trim();
String apellido = txtApellidoMecanico.getText().trim();
String telefono = txtTelMecanico.getText().trim();
String especialidad = txtEspecialidadMecanico.getText().trim();
String tarifaTxt = txtTarifaMecanico.getText().trim();

if (codigoTxt.isEmpty() || nombre.isEmpty() || apellido.isEmpty()
        || telefono.isEmpty() || especialidad.isEmpty() || tarifaTxt.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(this,
            "Debe completar todos los campos.");
    return;
}

int codigo;
float tarifa;
try {
    codigo = Integer.parseInt(codigoTxt);
    tarifa = Float.parseFloat(tarifaTxt);
} catch (NumberFormatException e) {
    javax.swing.JOptionPane.showMessageDialog(this,
            "Código y tarifa deben ser números válidos.");
    return;
}
if (!telefono.matches("\\d+")) {
    javax.swing.JOptionPane.showMessageDialog(this,
            "El teléfono debe contener solo números.");
    txtTelMecanico.requestFocus();
    txtTelMecanico.selectAll();
    return;
}

Mecanicos mecanico = new Mecanicos(codigo, nombre, apellido,
        telefono, especialidad, tarifa);

if (modoModificar) {
    servicio.modificar(mecanico);
    javax.swing.JOptionPane.showMessageDialog(this, "Mecánico modificado.");
    modoModificar = false;
    txtCodigoMecanico.setEnabled(true);
} else {
    if (!servicio.guardar(mecanico)) {
        javax.swing.JOptionPane.showMessageDialog(this,
                "Ya existe un mecánico con ese código.");
        return;
    }
    javax.swing.JOptionPane.showMessageDialog(this, "Mecánico guardado.");
}

actualizarTabla();
limpiarCampos();
        // TODO add your handling code here:
    }//GEN-LAST:event_btnGuardarActionPerformed
private void limpiarCampos() {
     txtCodigoMecanico.setText("");
    txtNombreMecanico.setText("");
    txtApellidoMecanico.setText("");
    txtTelMecanico.setText("");
    txtEspecialidadMecanico.setText("");
    txtTarifaMecanico.setText("");
    txtCodigoMecanico.setEnabled(true);
    modoModificar = false;
    tblMecanicos.clearSelection();
}
private void cargarCampos(Mecanicos m) {
    txtCodigoMecanico.setText(String.valueOf(m.getCodigo()));
    txtNombreMecanico.setText(m.getNombre());
    txtApellidoMecanico.setText(m.getApellido());
    txtTelMecanico.setText(m.getTelefono());
    txtEspecialidadMecanico.setText(m.getEspecialidad());
    txtTarifaMecanico.setText(String.valueOf(m.getTarifa()));
}
    

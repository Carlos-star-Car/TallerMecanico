private void actualizarTabla() {
  
    actualizarTabla(servicio.listar());
}
private void cargarCamposDesdeTabla() {
    int fila = tblProveedores.getSelectedRow();
    if (fila < 0) {
        return;
    }
    txtCodigoProveedor.setText(String.valueOf(tblProveedores.getValueAt(fila, 0)));
    txtNombreEmpresa.setText(String.valueOf(tblProveedores.getValueAt(fila, 1)));
    txtNombreContacto.setText(String.valueOf(tblProveedores.getValueAt(fila, 2)));
    txtTelEmpresa.setText(String.valueOf(tblProveedores.getValueAt(fila, 3)));
    txtCorreoEmpresa.setText(String.valueOf(tblProveedores.getValueAt(fila, 4)));
    txtDireccionEmpresa.setText(String.valueOf(tblProveedores.getValueAt(fila, 5)));
}

private void actualizarTabla(java.util.List<Proveedores> lista) {
    javax.swing.table.DefaultTableModel modelo = new javax.swing.table.DefaultTableModel(
            new String[]{"Código", "Empresa", "Contacto", "Teléfono", "Correo", "Dirección"}, 0) {
        @Override
        public boolean isCellEditable(int row, int column) {
            return false;
        }
    };
    for (Proveedores p : lista) {
        modelo.addRow(new Object[]{p.getCodigoProveedor(), p.getNombreEmpresa(), p.getNombreContacto(),
            p.getTelefono(), p.getCorreo(), p.getDireccion()});
    }
    tblProveedores.setModel(modelo);
}
private void limpiarCampos() {
    txtCodigoProveedor.setText("");
    txtNombreEmpresa.setText("");
    txtNombreContacto.setText("");
    txtTelEmpresa.setText("");
    txtCorreoEmpresa.setText("");
    txtDireccionEmpresa.setText("");
    txtCodigoProveedor.setEnabled(true);
    modoModificar = false;
    tblProveedores.clearSelection();
    txtCodigoProveedor.requestFocus();
}

    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed

     String codigoTxt = txtCodigoProveedor.getText().trim();
String nombreEmpresa = txtNombreEmpresa.getText().trim();
String nombrecontacto = txtNombreContacto.getText().trim();
String telefono = txtTelEmpresa.getText().trim();
String correo = txtCorreoEmpresa.getText().trim();
String direccion = txtDireccionEmpresa.getText().trim();

if (codigoTxt.isEmpty() || nombreEmpresa.isEmpty() || nombrecontacto.isEmpty()
        || telefono.isEmpty() || correo.isEmpty() || direccion.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(this,
            "Debe completar todos los campos.");
    return;
}


int codigo;

try {
    codigo = Integer.parseInt(codigoTxt);
    
} catch (NumberFormatException e) {
    javax.swing.JOptionPane.showMessageDialog(this,
            "Código debe ser números válidos.");
    return;
}

if (!telefono.matches("\\d+")) {
    javax.swing.JOptionPane.showMessageDialog(this,
            "El teléfono debe contener solo números.");
    txtTelEmpresa.requestFocus();
    txtTelEmpresa.selectAll();
    return;
}

Proveedores proveedor = new Proveedores(codigo, nombreEmpresa, nombrecontacto,
        telefono, correo, direccion);

if (modoModificar) {
    servicio.modificar(proveedor);
    javax.swing.JOptionPane.showMessageDialog(this, "Proveedor modificado.");
    modoModificar = false;
    txtCodigoProveedor.setEnabled(true);
} else {
    if (!servicio.guardar(proveedor)) {
        javax.swing.JOptionPane.showMessageDialog(this,
                "Ya existe un proveedor con ese código.");
        return;
    }
    javax.swing.JOptionPane.showMessageDialog(this, "Proveedor guardado.");
}


actualizarTabla();
limpiarCampos();
        // TODO add your handling code here:
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnModificarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnModificarActionPerformed
    if (tblProveedores.getSelectedRow() < 0) {
        javax.swing.JOptionPane.showMessageDialog(this,
                "Seleccione un proveedor de la lista para modificar.");
        return;
    }
    cargarCamposDesdeTabla();
    modoModificar = true;
    txtCodigoProveedor.setEnabled(false);   // el código no se puede cambiar
    txtNombreEmpresa.requestFocus();
        // TODO add your handling code here:
    }//GEN-LAST:event_btnModificarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed

    int fila = tblProveedores.getSelectedRow();
    if (fila < 0) {
        javax.swing.JOptionPane.showMessageDialog(this,
                "Seleccione un proveedor de la lista para eliminar.");
        return;
    }
    int codigo = (int) tblProveedores.getValueAt(fila, 0);
    String empresa = String.valueOf(tblProveedores.getValueAt(fila, 1));

    int opcion = javax.swing.JOptionPane.showConfirmDialog(this,
            "¿Desea eliminar al proveedor " + empresa + " (código " + codigo + ")?",
            "Confirmar eliminación",
            javax.swing.JOptionPane.YES_NO_OPTION,
            javax.swing.JOptionPane.QUESTION_MESSAGE);

    if (opcion == javax.swing.JOptionPane.YES_OPTION) {
        if (servicio.eliminar(codigo)) {
            javax.swing.JOptionPane.showMessageDialog(this, "Proveedor eliminado.");
            actualizarTabla();
            limpiarCampos();
        } else {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "No se pudo eliminar el proveedor. Verifique que ningún repuesto lo esté usando.");
        }
    }
        // TODO add your handling code here:
    }//GEN-LAST:event_btnEliminarActionPerformed


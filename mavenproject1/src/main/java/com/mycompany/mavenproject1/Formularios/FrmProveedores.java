    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
  String criterio = txtCodigoProveedor.getText().trim();
    if (criterio.isEmpty()) {
        criterio = txtNombreEmpresa.getText().trim();
    }
    if (criterio.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this,
                "Ingrese un código o nombre de empresa para buscar.");
        return;
    }

    java.util.List<Proveedores> resultado = servicio.buscar(criterio);
    if (resultado.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "El proveedor no existe.");
        limpiarCampos();
        actualizarTabla();
    } else {
        actualizarTabla(resultado);
        tblProveedores.setRowSelectionInterval(0, 0);   // carga el primero en los campos
    }
        // TODO add your handling code here:
    }//GEN-LAST:event_btnBuscarActionPerformed

    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed

        String codigoTxt = txtCodigoRepuesto.getText().trim();
        String nombre = txtNombRepuesto.getText().trim();
        String existenciaTxt = txtCantidadExistencia.getText().trim();
        String unidad = txtUnidadDeMedida.getText().trim();
        String precioTxt = txtPrecioUnitario.getText().trim();

        if (codigoTxt.isEmpty() || nombre.isEmpty() || existenciaTxt.isEmpty()
                || unidad.isEmpty() || precioTxt.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Debe completar todos los campos.");
            return;
        }

        int codigo;
        try {
            codigo = Integer.parseInt(codigoTxt);
        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "El código debe ser un número entero.");
            txtCodigoRepuesto.requestFocus();
            return;
        }

        int existencia;
        try {
            existencia = Integer.parseInt(existenciaTxt);
            if (existencia < 0) {
                throw new NumberFormatException();
            }
        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "La existencia debe ser un número entero igual o mayor a 0.");
            txtCantidadExistencia.requestFocus();
            return;
        }

        double precio;
        try {
            precio = Double.parseDouble(precioTxt);
            if (precio <= 0) {
                throw new NumberFormatException();
            }
        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "El precio unitario debe ser un número mayor a 0.");
            txtPrecioUnitario.requestFocus();
            return;
        }

        int codigoCategoria = codigoDeCombo(jCBCodCategoria);
        int codigoProveedor = codigoDeCombo(jCBCodProveedor);
        if (codigoCategoria < 0 || codigoProveedor < 0) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Debe seleccionar una categoría y un proveedor. "
                    + "Si las listas están vacías, registre primero categorías y proveedores.");
            return;
        }

        Repuesto repuesto = new Repuesto(codigo, nombre, existencia, unidad, precio,
                codigoCategoria, codigoProveedor);

        if (modoModificar) {
            servicio.modificar(repuesto);
            javax.swing.JOptionPane.showMessageDialog(this, "Repuesto modificado.");
        } else {
            if (!servicio.guardar(repuesto)) {
                javax.swing.JOptionPane.showMessageDialog(this, "Ya existe un repuesto con ese código.");
                return;
            }
            javax.swing.JOptionPane.showMessageDialog(this, "Repuesto guardado.");
        }
        actualizarTabla();
        limpiarCampos();
        // TODO add your handling code here:
    }//GEN-LAST:event_btnGuardarActionPerformed


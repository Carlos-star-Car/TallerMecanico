    private void cargarCombos() {
        jCBCodCategoria.removeAllItems();
        for (CategoriaRepuesto c : CategoriaRepuestoServicio.getInstancia().listar()) {
            jCBCodCategoria.addItem(c.getCodigo() + " - " + c.getNombre());
        }
        jCBCodProveedor.removeAllItems();
        for (Proveedores p : new ProveedoresServicio().listar()) {
            jCBCodProveedor.addItem(p.getCodigoProveedor() + " - " + p.getNombreEmpresa());
        }
    }

// El combo muestra "codigo - nombre"; esto devuelve solo el código (o -1 si no hay selección)
    private int codigoDeCombo(javax.swing.JComboBox<String> combo) {
        Object seleccionado = combo.getSelectedItem();
        if (seleccionado == null) {
            return -1;
        }
        return Integer.parseInt(seleccionado.toString().split(" - ")[0].trim());
    }

    private void seleccionarEnCombo(javax.swing.JComboBox<String> combo, int codigo) {
        for (int i = 0; i < combo.getItemCount(); i++) {
            if (combo.getItemAt(i).startsWith(codigo + " - ")) {
                combo.setSelectedIndex(i);
                return;
            }
        }
        combo.setSelectedIndex(-1);
    }

    private void actualizarTabla() {
        actualizarTabla(servicio.listar());
    }

    private void actualizarTabla(java.util.List<Repuesto> lista) {
        javax.swing.table.DefaultTableModel modelo = new javax.swing.table.DefaultTableModel(
                new String[]{"Código", "Nombre", "Existencia", "Unidad", "Precio", "Categoría", "Proveedor"}, 0) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };
        for (Repuesto r : lista) {
            modelo.addRow(new Object[]{r.getCodigoRepuesto(), r.getNombreRepuesto(), r.getExistencia(),
                r.getUnidadMedida(), r.getPrecioUnitario(), r.getCodigoCategoria(), r.getCodigoProveedor()});
        }
        tblRepuesto.setModel(modelo);
    }

    private void cargarCamposDesdeTabla() {
        int fila = tblRepuesto.getSelectedRow();
        if (fila < 0) {
            return;
        }
        txtCodigoRepuesto.setText(String.valueOf(tblRepuesto.getValueAt(fila, 0)));
        txtNombRepuesto.setText(String.valueOf(tblRepuesto.getValueAt(fila, 1)));
        txtCantidadExistencia.setText(String.valueOf(tblRepuesto.getValueAt(fila, 2)));
        txtUnidadDeMedida.setText(String.valueOf(tblRepuesto.getValueAt(fila, 3)));
        txtPrecioUnitario.setText(String.valueOf(tblRepuesto.getValueAt(fila, 4)));
        seleccionarEnCombo(jCBCodCategoria, (int) tblRepuesto.getValueAt(fila, 5));
        seleccionarEnCombo(jCBCodProveedor, (int) tblRepuesto.getValueAt(fila, 6));
    }

    private void limpiarCampos() {
        txtCodigoRepuesto.setText("");
        txtNombRepuesto.setText("");
        txtCantidadExistencia.setText("");
        txtUnidadDeMedida.setText("");
        txtPrecioUnitario.setText("");
        if (jCBCodCategoria.getItemCount() > 0) {
            jCBCodCategoria.setSelectedIndex(0);
        }
        if (jCBCodProveedor.getItemCount() > 0) {
            jCBCodProveedor.setSelectedIndex(0);
        }
        txtCodigoRepuesto.setEnabled(true);
        modoModificar = false;
        tblRepuesto.clearSelection();
        txtCodigoRepuesto.requestFocus();
    }

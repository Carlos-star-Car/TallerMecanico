    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
 int fila = tblRepuesto.getSelectedRow();
    if (fila < 0) {
        javax.swing.JOptionPane.showMessageDialog(this,
                "Seleccione un repuesto de la lista para eliminar.");
        return;
    }
    int codigo = (int) tblRepuesto.getValueAt(fila, 0);
    String nombre = String.valueOf(tblRepuesto.getValueAt(fila, 1));

    int opcion = javax.swing.JOptionPane.showConfirmDialog(this,
            "¿Desea eliminar el repuesto " + nombre + " (código " + codigo + ")?",
            "Confirmar eliminación",
            javax.swing.JOptionPane.YES_NO_OPTION,
            javax.swing.JOptionPane.QUESTION_MESSAGE);

    if (opcion == javax.swing.JOptionPane.YES_OPTION) {
        servicio.eliminar(codigo);
        javax.swing.JOptionPane.showMessageDialog(this, "Repuesto eliminado.");
        actualizarTabla();
        limpiarCampos();
    }
        // TODO add your handling code here:
    }//GEN-LAST:event_btnEliminarActionPerformed

    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
 String criterio = txtCodigoRepuesto.getText().trim();
    if (criterio.isEmpty()) {
        criterio = txtNombRepuesto.getText().trim();
    }
    if (criterio.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this,
                "Ingrese un código o nombre de repuesto para buscar.");
        return;
    }

    java.util.List<Repuesto> resultado = servicio.buscar(criterio);
    if (resultado.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "El repuesto no existe.");
        limpiarCampos();
        actualizarTabla();
    } else {
        actualizarTabla(resultado);
        tblRepuesto.setRowSelectionInterval(0, 0);   // carga el primero en los campos
    }
        // TODO add your handling code here:
    }//GEN-LAST:event_btnBuscarActionPerformed
    private void cargarImagenlogo() {
        java.net.URL url = getClass().getResource("/logotaller.png");
        if (url == null) {
            System.out.println("No se encontró la imagen");
            return;
        }
        javax.swing.ImageIcon icono = new javax.swing.ImageIcon(url);
        java.awt.Image escalada = icono.getImage().getScaledInstance(
                260, 100, java.awt.Image.SCALE_SMOOTH);
        lbllogo.setIcon(new javax.swing.ImageIcon(escalada));
        lbllogo.setText("");
    }


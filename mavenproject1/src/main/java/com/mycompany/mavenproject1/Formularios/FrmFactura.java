    private void cargarFilaSeleccionada() {
        if (modoConsulta) return;
          int fila = tblDetalleFactura.getSelectedRow();
        if (fila < 0 || fila >= detalles.size()) {
            return;
        }
        DetalleFactura d = detalles.get(fila);
        if (conceptoEsCombo && d.esRepuesto()) {
            for (int i = 0; i < repuestosEnCombo.size(); i++) {
                if (repuestosEnCombo.get(i).getCodigoRepuesto() == d.getCodigoRepuesto()) {
                    cbRepuesto.setSelectedIndex(i + 1);
                    break;
                }
            }
        } else {
            txtConcepto.setText(d.getConcepto());
        }
        txtCantidad.setText(String.valueOf(d.getCantidad()));
        txtPrecioUnitario.setText(String.valueOf(d.getPrecioUnitario()));
    }

    // Lee y valida los campos. filaExcluida = fila que se está modificando (-1 si es nueva).
    private DetalleFactura leerDetalleDeCampos(int filaExcluida) {
        DetalleFactura d = new DetalleFactura();
        Repuesto repuesto = null;

        if (conceptoEsCombo) {
            repuesto = repuestoSeleccionado();
            if (repuesto == null) {
                aviso("Seleccione el repuesto.");
                cbRepuesto.requestFocus();
                return null;
            }
            d.setConcepto(repuesto.getNombreRepuesto());
            d.setCodigoRepuesto(repuesto.getCodigoRepuesto());
            d.setPrecioUnitario(repuesto.getPrecioUnitario());   // siempre el del inventario
        } else {
            String concepto = txtConcepto.getText().trim();
            if (concepto.isEmpty()) {
                aviso("Ingrese el concepto.");
                txtConcepto.requestFocus();
                return null;
            }
            d.setConcepto(concepto);
        }

        int cantidad;
        try {
            cantidad = Integer.parseInt(txtCantidad.getText().trim());
        } catch (NumberFormatException ex) {
            aviso("La cantidad debe ser un número entero.");
            txtCantidad.requestFocus();
            return null;
        }
        if (cantidad <= 0) {
            aviso("La cantidad debe ser mayor a cero.");
            txtCantidad.requestFocus();
            return null;
        }
        d.setCantidad(cantidad);

        if (repuesto != null) {
            int yaAgregado = cantidadEnDetalle(repuesto.getCodigoRepuesto(), filaExcluida);
            if (yaAgregado + cantidad > repuesto.getExistencia()) {
                aviso("Existencia insuficiente de " + repuesto.getNombreRepuesto()
                        + ". Disponible: " + repuesto.getExistencia()
                        + ", ya agregado a esta factura: " + yaAgregado + ".");
                txtCantidad.requestFocus();
                return null;
            }
        } else {
            double precio;
            try {
                precio = Double.parseDouble(txtPrecioUnitario.getText().trim().replace(",", "."));
            } catch (NumberFormatException ex) {
                aviso("El precio unitario debe ser un número.");
                txtPrecioUnitario.requestFocus();
                return null;
            }
            if (precio <= 0) {
                aviso("El precio unitario debe ser mayor a cero.");
                txtPrecioUnitario.requestFocus();
                return null;
            }
            d.setPrecioUnitario(precio);
        }
        return d;
    }

    private void limpiarCamposDetalle() {
        txtConcepto.setText("");
        if (cbRepuesto.getItemCount() > 0) {
            cbRepuesto.setSelectedIndex(0);
        }
        txtCantidad.setText("");
        txtPrecioUnitario.setText("");
        tblDetalleFactura.clearSelection();
        if (conceptoEsCombo) {
            cbRepuesto.requestFocus();
        } else {
            txtConcepto.requestFocus();
        }
    }

    // Lee y valida los tres campos. Devuelve null (con aviso) si algo está mal.
    private DetalleFactura leerDetalleDeCampos() {
        String concepto = txtConcepto.getText().trim();
        if (concepto.isEmpty()) {
            aviso("Ingrese el concepto.");
            txtConcepto.requestFocus();
            return null;
        }

        int cantidad;
        try {
            cantidad = Integer.parseInt(txtCantidad.getText().trim());
        } catch (NumberFormatException ex) {
            aviso("La cantidad debe ser un número entero.");
            txtCantidad.requestFocus();
            return null;
        }
        if (cantidad <= 0) {
            aviso("La cantidad debe ser mayor a cero.");
            txtCantidad.requestFocus();
            return null;
        }

        double precio;
        try {
            precio = Double.parseDouble(txtPrecioUnitario.getText().trim().replace(",", "."));
        } catch (NumberFormatException ex) {
            aviso("El precio unitario debe ser un número.");
            txtPrecioUnitario.requestFocus();
            return null;
        }
        if (precio <= 0) {
            aviso("El precio unitario debe ser mayor a cero.");
            txtPrecioUnitario.requestFocus();
            return null;
        }

        DetalleFactura d = new DetalleFactura();
        d.setConcepto(concepto);
        d.setCantidad(cantidad);
        d.setPrecioUnitario(precio);
        return d;
    }

    // "Cancelar detalle": quita de la factura la fila seleccionada.
    private void quitarDetalleSeleccionado() {
        int fila = tblDetalleFactura.getSelectedRow();
        if (fila < 0) {
            aviso("Seleccione en la tabla el detalle que desea cancelar.");
            return;
        }
        detalles.remove(fila);
        refrescarTablaDetalle();
        limpiarCamposDetalle();
    }

  

    private void limpiarTodoElDetalle() {
        detalles.clear();
        refrescarTablaDetalle();
        limpiarCamposDetalle();
    }

    // Vuelve a dibujar la tabla y recalcula los totales.
    private void refrescarTablaDetalle() {
        modeloDetalle.setRowCount(0);
        for (DetalleFactura d : detalles) {
            modeloDetalle.addRow(new Object[]{
                d.getConcepto(),
                d.getCantidad(),
                formato(d.getPrecioUnitario()),
                formato(d.getSubtotal())
            });
        }
        recalcularTotales();
    }

    // El cálculo vive en Factura, así que usamos una temporal con el mismo detalle.
    private void recalcularTotales() {
        Factura calculo = new Factura();
        calculo.setDetalles(detalles);
        txtSubtotal.setText(formato(calculo.getSubtotal()));
        txtIva.setText(formato(calculo.getIva()));
        txtTotal.setText(formato(calculo.getTotal()));
    }

    private String formato(double valor) {
        return String.format(java.util.Locale.US, "%.2f", valor);
    }


    private void guardarFactura() {
        Factura f = new Factura();

        if (jRBOrdenServicio.isSelected()) {
            f.setTipoFactura(Factura.TIPO_SERVICIO);
            if (CdOrdenSi.isSelected()) {
                if (jCBCodigoOrden.getSelectedIndex() <= 0) {
                    aviso("Seleccione el código de la orden.");
                    return;
                }
                String codigo = (String) jCBCodigoOrden.getSelectedItem();
                OrdenDeTrabajo orden = OrdenDeTrabajoServicio.getInstancia().buscarPorCodigo(codigo);
                if (orden == null) {
                    aviso("La orden de trabajo no existe.");
                    return;
                }
                f.setIdOrden(codigo);
                f.setCliente(orden.getCliente());
            } else if (CdOrdenNo.isSelected()) {
                f.setNombreManual(txtNombreCliente.getText().trim());
                f.setNitManual(txtNit.getText().trim());
                f.setDireccionManual(txtDireccion.getText().trim());
            } else {
                aviso("Indique si la factura tiene código de orden (Sí o No).");
                return;
            }
        } else if (jRBRepuesto.isSelected()) {
            f.setTipoFactura(Factura.TIPO_REPUESTO);
        }

        f.setDetalles(new java.util.ArrayList<>(detalles));
        f.setFechaEmision(LocalDate.now());

        String error = FacturaServicio.getInstancia().validar(f);
        if (error != null) {
            aviso(error);
            return;
        }
        FacturaServicio.getInstancia().guardar(f);
        aviso("Factura No. " + f.getIdFactura() + " guardada.\nTotal: Q " + formato(f.getTotal()));
        iniciarFormulario();
    }

    // Consulta: pide el número y muestra la factura en solo lectura.
    private void buscarFactura() {
        String texto = javax.swing.JOptionPane.showInputDialog(this,
                "Ingrese el número de factura a consultar:", "Buscar factura",
                javax.swing.JOptionPane.QUESTION_MESSAGE);
        if (texto == null) {
            return;   // canceló
        }
        int numero;
        try {
            numero = Integer.parseInt(texto.trim());
        } catch (NumberFormatException ex) {
            aviso("El número de factura debe ser un número entero.");
            return;
        }
        Factura f = FacturaServicio.getInstancia().buscarPorCodigo(numero);
        if (f == null) {
            aviso("No existe la factura No. " + numero + ".");
            return;
        }
        mostrarFactura(f);
    }

    private void mostrarFactura(Factura f) {
        facturaConsultada = f;
        ponerModoConsulta(true);
        setTitle("Factura No. " + f.getIdFactura() + " - " + f.getEstado());

        txtCodigofactura.setText(String.valueOf(f.getIdFactura()));
        txtFechaEmision.setText(f.getFechaEmision().format(FORMATO_FECHA));

        if (Factura.TIPO_REPUESTO.equals(f.getTipoFactura())) {
            jRBRepuesto.setSelected(true);
        } else {
            jRBOrdenServicio.setSelected(true);
        }

        // La orden puede estar ya facturada y no figurar en el combo, por eso se muestra sola.
        if (f.getIdOrden() != null) {
            jCBCodigoOrden.setModel(new javax.swing.DefaultComboBoxModel<>(new String[]{f.getIdOrden()}));
            CdOrdenSi.setSelected(true);
        } else {
            jCBCodigoOrden.setModel(new javax.swing.DefaultComboBoxModel<>(new String[]{"-- Seleccione --"}));
            if (Factura.TIPO_SERVICIO.equals(f.getTipoFactura())) {
                CdOrdenNo.setSelected(true);
            } else {
                grupoOrden.clearSelection();
            }
        }

        if (f.getCliente() != null) {
            txtNombreCliente.setText(f.getCliente().getNombreCompleto());
            txtNit.setText(f.getCliente().getNit());
            txtDireccion.setText(f.getCliente().getDireccion());
        } else {
            txtNombreCliente.setText(f.getNombreManual() == null ? "" : f.getNombreManual());
            txtNit.setText(f.getNitManual() == null ? "" : f.getNitManual());
            txtDireccion.setText(f.getDireccionManual() == null ? "" : f.getDireccionManual());
        }

        mostrarConceptoComoCombo(false);
        txtConcepto.setText("");
        txtCantidad.setText("");
        txtPrecioUnitario.setText("");

        detalles.clear();
        detalles.addAll(f.getDetalles());
        refrescarTablaDetalle();   // también recalcula subtotal, IVA y total
    }

    private void anularFactura() {
        if (facturaConsultada == null) {
            aviso("Use Buscar para consultar la factura que desea anular.");
            return;
        }
        int respuesta = javax.swing.JOptionPane.showConfirmDialog(this,
                "¿Anular la factura No. " + facturaConsultada.getIdFactura() + "?\n"
                + "Los repuestos regresarán al inventario y la orden de trabajo "
                + "volverá a quedar pendiente.\nEsta acción no se puede deshacer.",
                "Anular factura", javax.swing.JOptionPane.YES_NO_OPTION,
                javax.swing.JOptionPane.WARNING_MESSAGE);
        if (respuesta != javax.swing.JOptionPane.YES_OPTION) {
            return;
        }
        String error = FacturaServicio.getInstancia().anular(facturaConsultada.getIdFactura());
        if (error != null) {
            aviso(error);
            return;
        }
        aviso("Factura No. " + facturaConsultada.getIdFactura() + " anulada.");
        mostrarFactura(facturaConsultada);   // se vuelve a mostrar, ahora como ANULADA
    }

    // Bloquea todo para consultar, o deja el formulario listo para facturar.
    private void ponerModoConsulta(boolean consulta) {
        modoConsulta = consulta;
        boolean editable = !consulta;

        jRBOrdenServicio.setEnabled(editable);
        jRBRepuesto.setEnabled(editable);
        txtConcepto.setEnabled(editable);
        cbRepuesto.setEnabled(editable);
        txtCantidad.setEnabled(editable);
        txtPrecioUnitario.setEnabled(editable);
        btnAgregarADetalleFactura.setEnabled(editable);
        btnModificarDetalleFactura.setEnabled(editable);
        btnLimpiarDetalleFactura.setEnabled(editable);
        btnCancelarDetalle.setEnabled(editable);
        btnGuardar.setEnabled(editable);

        if (consulta) {
            CdOrdenSi.setEnabled(false);
            CdOrdenNo.setEnabled(false);
            jCBCodigoOrden.setEnabled(false);
            // Habilitados pero no editables, para que el texto se lea bien.
            txtNombreCliente.setEnabled(true);
            txtNit.setEnabled(true);
            txtDireccion.setEnabled(true);
            txtNombreCliente.setEditable(false);
            txtNit.setEditable(false);
            txtDireccion.setEditable(false);
            btnAnular.setEnabled(facturaConsultada != null && !facturaConsultada.estaAnulada());
        } else {
            facturaConsultada = null;
            btnAnular.setEnabled(false);
            // Sí/No, combo y datos de cliente los ajusta actualizarControles().
        }
    }

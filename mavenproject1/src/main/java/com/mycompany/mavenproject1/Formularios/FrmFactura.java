    // Cambia el campo Concepto por el combo de repuestos (o lo devuelve).
    private void mostrarConceptoComoCombo(boolean comoCombo) {
        if (comoCombo == conceptoEsCombo) {
            return;
        }
        javax.swing.GroupLayout layout = (javax.swing.GroupLayout) AgregarDetalle.getLayout();
        if (comoCombo) {
            layout.replace(txtConcepto, cbRepuesto);
        } else {
            layout.replace(cbRepuesto, txtConcepto);
        }
        conceptoEsCombo = comoCombo;
        AgregarDetalle.revalidate();
        AgregarDetalle.repaint();
    }
        private void cargarRepuestosEnCombo() {
        repuestosEnCombo = repuestoServicio.listar();
        javax.swing.DefaultComboBoxModel<String> modelo = new javax.swing.DefaultComboBoxModel<>();
        modelo.addElement("-- Seleccione --");
        for (Repuesto r : repuestosEnCombo) {
            modelo.addElement(r.getNombreRepuesto() + " (existencia: " + r.getExistencia() + ")");
        }
        cbRepuesto.setModel(modelo);
    }

    private Repuesto repuestoSeleccionado() {
        int i = cbRepuesto.getSelectedIndex();
        if (i <= 0 || i > repuestosEnCombo.size()) {
            return null;
        }
        return repuestosEnCombo.get(i - 1);
    }

    // Al elegir un repuesto, el precio se llena solo.
    private void alElegirRepuesto() {
        if (modoConsulta) return;
        Repuesto r = repuestoSeleccionado();
        txtPrecioUnitario.setText(r == null ? "" : String.valueOf(r.getPrecioUnitario()));
    }

    // Unidades de ese repuesto que ya están en el detalle (sin contar la fila que se modifica).
    private int cantidadEnDetalle(int codigoRepuesto, int filaExcluida) {
        int total = 0;
        for (int i = 0; i < detalles.size(); i++) {
            DetalleFactura x = detalles.get(i);
            if (i != filaExcluida && x.esRepuesto() && x.getCodigoRepuesto() == codigoRepuesto) {
                total += x.getCantidad();
            }
        }
        return total;
    }

    // Al elegir una orden, llena automáticamente los datos del cliente.
    private void alElegirOrden() {
        if (modoConsulta) return;
        if (!CdOrdenSi.isSelected() || jCBCodigoOrden.getSelectedIndex() <= 0) {
            limpiarDatosCliente();
            return;
        }
        String codigo = (String) jCBCodigoOrden.getSelectedItem();
        OrdenDeTrabajo orden = OrdenDeTrabajoServicio.getInstancia().buscarPorCodigo(codigo);
        if (orden == null || orden.getCliente() == null) {
            limpiarDatosCliente();
            return;
        }
        Cliente c = orden.getCliente();
        txtNombreCliente.setText(c.getNombreCompleto());
        txtNit.setText(c.getNit());
        txtDireccion.setText(c.getDireccion());
    }

